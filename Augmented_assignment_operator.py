# Augmented Assignment Operators in Python

# Addition & Assignment
a = 15
b = 20
a += b
print("Addition & Assignment (+=):", a)  # 35

# Subtraction & Assignment
a = 107
b = 99
a -= b
print("Subtraction & Assignment (-=):", a)  # 8

# Multiplication & Assignment
a = 12
b = 23
a *= b
print("Multiplication & Assignment (*=):", a)  # 276

# Division & Assignment
a = 56
b = 5
a /= b
print("Division & Assignment (/=):", a)  # 11.2

# Floor Division & Assignment
a = -55
b = 8
a //= b
print("Floor Division & Assignment (//=):", a)  # 7

# Modulo & Assignment
a = 34
b = 5
a %= b
print("Modulo & Assignment (%=):", a)  # 4

# Power & Assignment
a = 5
b = 3
a **= b
print("Power & Assignment (**=):", a)  # 125

# Bitwise AND & Assignment
a = 12
b = 10
a &= b
print("Bitwise AND & Assignment (&=):", a)  # 8

# Bitwise OR & Assignment
a = 12
b = 10
a |= b
print("Bitwise OR & Assignment (|=):", a)  # 14

# Bitwise XOR & Assignment
a = 12
b = 10
a ^= b
print("Bitwise XOR & Assignment (^=):", a)  # 6

# Bitwise Left Shift & Assignment
a = 17
b = 2
a <<= b
print("Bitwise Left Shift & Assignment (<<=):", a)  # 68

# Bitwise Right Shift & Assignment
a = 17
b = 2
a >>= b
print("Bitwise Right Shift & Assignment (>>=):", a)  # 4
