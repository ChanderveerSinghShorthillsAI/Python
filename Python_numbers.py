# Integer (int)
x = 10
print(x, "is of type", type(x))

# Floating point (float)
y = 10.5
print(y, "is of type", type(y))

# Complex number (complex)
z = 3 + 4j
print(z, "is of type", type(z))

# # Output
# 10 is of type <class 'int'>
# 10.5 is of type <class 'float'>
# (3+4j) is of type <class 'complex'>
