# Escape Characters in Python



# 1. Newline (\n)
print("\nNewline Example:\nHello, World!\nWelcome to Python.")

# 2. Tab (\t)
print("\nTab Example:\nName\tAge\tLocation")

# 3. Backslash (\\)
print("\nBackslash Example:\nThis is a backslash: \\")

# 4. Single Quote (\'')
print("\nSingle Quote Example:\nIt\'s a great day!")

# 5. Double Quote (\")
print("\nDouble Quote Example:\nHe said, \"Hello!\"")

# 6. Carriage Return (\r)
print("\nCarriage Return Example:\nHello, World!\rHi")

# 7. Backspace (\b)
print("\nBackspace Example:\nHello, World!\b")  # Removes the last character# The last character might not be visibly removed in some consoles

# 8. Form Feed (\f)
print("\nForm Feed Example:\nHello\fWorld!")  # Not commonly used in modern systems

# 9. Vertical Tab (\v)
print("\nVertical Tab Example:\nHello\vWorld!")  # Moves cursor vertically

# 10. Hexadecimal (\xhh)
print("\nHexadecimal Example:\nHello \x48\x65\x6C\x6C\x6F")  # Prints "Hello Hello"