import math

# Trigonometry
print("math.sin(math.pi/2):", math.sin(math.pi/2))  # Sine of 90 degrees
print("math.cos(math.pi):", math.cos(math.pi))  # Cosine of 180 degrees
print("math.tan(math.pi/4):", math.tan(math.pi/4))  # Tangent of 45 degrees

# Logarithmic and Exponential Functions
print("math.log(10):", math.log(10))  # Natural log
print("math.log10(100):", math.log10(100))  # Base-10 log
print("math.exp(2):", math.exp(2))  # e^2
print("math.pow(2, 3):", math.pow(2, 3))  # 2^3

# Rounding & Absolute Values
print("math.ceil(4.3):", math.ceil(4.3))  # Round up
print("math.floor(4.7):", math.floor(4.7))  # Round down
print("math.fabs(-10):", math.fabs(-10))  # Absolute value

# Factorial & Combinations
print("math.factorial(5):", math.factorial(5))  # 5!
print("math.comb(5, 2):", math.comb(5, 2))  # Combinations C(5,2)

# GCD & Square Root
print("math.gcd(54, 24):", math.gcd(54, 24))  # Greatest Common Divisor
print("math.sqrt(16):", math.sqrt(16))  # Square root

# Hypotenuse & Distance
print("math.hypot(3, 4):", math.hypot(3, 4))  # Hypotenuse of (3,4)
print("math.dist([3, 4], [0, 0]):", math.dist([3, 4], [0, 0]))  # Distance between two points

# Constants
print("math.pi:", math.pi)  # Pi value
print("math.e:", math.e)  # Euler's number
print("math.inf:", math.inf)  # Infinity